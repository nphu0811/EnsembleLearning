def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def secure_output_dir(root: Path, raw: Path) -> Path:
    base = (root / "results/reproducibility").resolve(strict=True)
    location = raw if raw.is_absolute() else root / raw
    if location.exists() or location.is_symlink():
        raise ValueError("Output directory already exists; never overwrite P15 evidence")
    parent = location.parent.resolve(strict=True)
    if parent != base or not location.name.startswith("p15_local_artifact_qa_"):
        raise ValueError("Output must be a NEW direct reproducibility/p15_local_artifact_qa_* directory")
    return parent / location.name


def safe_artifact_path(worker_dir: Path, expected_name: str) -> Path:
    directory = worker_dir.resolve(strict=True)
    if worker_dir.is_symlink() or directory != worker_dir.absolute():
        raise ValueError("Model worker directory must not redirect through a link")
    artifact = worker_dir / expected_name
    if not artifact.is_file() or artifact.is_symlink() or artifact.resolve(strict=True).parent != directory:
        raise ValueError("Missing or unsafe model binary")
    return artifact


def file_integrity(path: Path, expected: dict) -> bool:
    if not path.is_file() or path.is_symlink():
        return False
    return (path.stat().st_size > 0
            and path.stat().st_size == expected.get("bytes")
            and sha256_file(path) == expected.get("sha256"))


def audit_csv_access(event, arguments) -> None:
    if event != "open" or not arguments or not isinstance(arguments[0], (str, bytes, os.PathLike)):
        return
    try:
        opened = Path(arguments[0]).resolve()
    except (OSError, ValueError, TypeError):
        return
    if opened.suffix.lower() == ".csv":
        if opened.name.lower() == "unsw_nb15_testing-set.csv":
            raise PermissionError("P15 artifact verification must not open official TEST")
        if (ROOT / "data") in opened.parents and opened != TRAIN:
            raise PermissionError("P15 artifact verification permits only official TRAIN dataset CSV")


def verify_fitted_configuration(name: str, model, frozen: dict, features: list[str]) -> dict:
    """Check loaded learned object, not a freshly rebuilt unfitted candidate."""
    from sklearn.ensemble import RandomForestClassifier, StackingClassifier
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import Pipeline
    checks: dict[str, bool] = {}
    def rf_checks(estimator, params: dict, prefix: str) -> None:
        checks[prefix + "_pipeline"] = isinstance(estimator, Pipeline)
        if not checks[prefix + "_pipeline"]:
            return
        model_step = estimator.named_steps.get("model")
        prep = estimator.named_steps.get("preprocess")
        checks[prefix + "_forest_type"] = isinstance(model_step, RandomForestClassifier)
        checks[prefix + "_preprocess_fitted"] = bool(
            prep is not None and hasattr(prep, "transformers_")
            and list(getattr(prep, "feature_names_in_", [])) == features
        )
        if checks[prefix + "_forest_type"]:
            checks[prefix + "_hyperparameters"] = all(
                getattr(model_step, key) == value for key, value in params.items()
            ) and model_step.random_state == 42 and model_step.n_jobs == -1
            checks[prefix + "_fitted_trees"] = (
                hasattr(model_step, "estimators_")
                and len(model_step.estimators_) == params["n_estimators"]
            )
    if name != "stacking_42":
        rf_checks(model, frozen[name]["hyperparameters"], name)
    else:
        cfg = frozen[name]
        checks["stack_type"] = isinstance(model, StackingClassifier)
        if checks["stack_type"]:
            checks["stack_fitted_base_count"] = hasattr(model, "estimators_") and len(model.estimators_) == 3
            checks["stack_schema"] = list(getattr(model, "feature_names_in_", [])) == features
            checks["stack_cv_frozen"] = (getattr(model.cv, "n_splits", None) == 3
                and model.cv.random_state == 137 and model.cv.shuffle is True)
            checks["stack_meta_fit"] = (
                isinstance(getattr(model, "final_estimator_", None), LogisticRegression)
                and model.final_estimator_.C == cfg["meta_learner"]["C"]
                and model.final_estimator_.solver == cfg["meta_learner"]["solver"]
                and hasattr(model.final_estimator_, "coef_")
            )
            checks["stack_execution_parameters"] = (model.n_jobs == 1
                and model.stack_method == "predict_proba" and model.passthrough is False)
            names = [name for name, _ in model.estimators]
            checks["stack_base_names"] = names == ["lr", "dt", "rf"]
            if checks["stack_fitted_base_count"] and checks["stack_base_names"]:
                lr, dt, rf = model.estimators_
                checks["stack_lr"] = (isinstance(lr, Pipeline)
                    and isinstance(lr.named_steps.get("model"), LogisticRegression)
                    and lr.named_steps["model"].C == cfg["base_learners"]["logistic_regression"]["C"]
                    and hasattr(lr.named_steps["model"], "coef_"))
                checks["stack_dt"] = (isinstance(dt, Pipeline)
                    and dt.named_steps["model"].min_samples_leaf ==
                    cfg["base_learners"]["decision_tree"]["min_samples_leaf"]
                    and hasattr(dt.named_steps["model"], "tree_"))
                rf_checks(rf, cfg["base_learners"]["random_forest"], "stack_rf")
    return checks


def verify_one(name: str, features: list[str], frozen: dict, probe, versions: dict) -> dict:
    import joblib
    import numpy as np

    work = BASE / RUNS[name]
    run = json.loads((work / "run_report.json").read_text(encoding="utf-8"))
    worker = json.loads((work / "worker/worker_result.json").read_text(encoding="utf-8"))
    artifact = worker.get("artifact", {})
    expected_name = name + "_RECONSTRUCTED_FULL_TRAIN.joblib"
    checks = {
        "supervisor_and_worker_pass": run.get("result") == "PASS" and worker.get("passed") is True,
        "identity_and_full_train": run.get("candidate") == name
             and worker.get("candidate") == name and run.get("mode") == "full"
             and worker.get("mode") == "full" and worker.get("train_rows") == 175341,
        "frozen_input_hashes": worker.get("input_sha256") == HASHES and run.get("source_hashes") == HASHES,
        "frozen_threshold_and_classes": worker.get("threshold") == frozen[name]["decision_threshold"]
             and worker.get("classes") == [0, 1],
        "features_and_order": worker.get("ordered_features") == features,
        "environment_match": worker.get("package_versions") == versions
             and run.get("package_versions") == versions,
        "clean_execution": run.get("exit_code") == 0 and run.get("stop_reason") is None,
        "not_original_model": artifact.get("scope") == "RECONSTRUCTED_FULL_TRAIN; NOT original trained artifact"
             and run.get("release_certified") is False,
        "local_artifact_filename": artifact.get("filename") == expected_name,
    }
    result = {"candidate": name, "checks": checks,
              "claimed_artifact_sha256": artifact.get("sha256"),
              "claimed_artifact_bytes": artifact.get("bytes")}
    if not all(checks.values()):
        result["passed"] = False
        return result
    try:
        path = safe_artifact_path(work / "worker", expected_name)
        checks["local_sha256_and_length"] = file_integrity(path, artifact)
        if not checks["local_sha256_and_length"]:
            result["passed"] = False
            return result
        # joblib is pickle based. Load ONLY locally generated trusted files.
        model = joblib.load(path)
        checks.update(verify_fitted_configuration(name, model, frozen, features))
        x = probe.loc[:, features].copy()
        checks["ordered_probe"] = list(x.columns) == features and len(x) == 16 and not x.isna().any().any()
        if checks["ordered_probe"]:
            prediction = model.predict_proba(x)
            checks["proba_shape_and_finite"] = prediction.shape == (16, 2) and bool(np.isfinite(prediction).all())
            checks["proba_normalized"] = (bool(((prediction >= 0) & (prediction <= 1)).all())
                and bool(np.allclose(prediction.sum(axis=1), 1.0, rtol=1e-12, atol=1e-12)))
            checks["class_order"] = list(model.classes_) == [0, 1]
        else:
            checks["proba_shape_and_finite"] = False
            checks["proba_normalized"] = False
            checks["class_order"] = False
        del model
        gc.collect()
        checks["hash_stable_after_reload"] = file_integrity(path, artifact)
    except (OSError, ValueError, RuntimeError, AttributeError, TypeError, KeyError) as exc:
        checks["independent_deserialize_and_predict"] = False
        result["failure"] = type(exc).__name__ + ": " + str(exc)[:200]
    result["passed"] = all(checks.values())
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", required=True, type=Path)
    args = parser.parse_args()
    target = secure_output_dir(ROOT, args.out_dir)
    target.mkdir(exist_ok=False)
    sys.dont_write_bytecode = True
    sys.addaudithook(audit_csv_access)
    results: dict = {"scope": "P15_LOCAL_ARTIFACT_READONLY_QA; NOT original model or scientific TEST validation",
                     "training_performed": False, "official_test_opened": False,
                     "run_names": RUNS, "results": {}, "passed": False}
    try:
        if sys.version_info[:2] != (3, 11):
            raise RuntimeError("Artifact QA requires Python 3.11 (same as P15 author environment)")
        for rel, digest in HASHES.items():
            if sha256_file(ROOT / rel) != digest:
                raise RuntimeError("Frozen input source changed: " + rel)
        import pandas as pd
        versions = {lib: importlib.metadata.version(lib) for lib in LIBRARIES}
        frozen = json.loads(FREEZE.read_text(encoding="utf-8"))
        stable = json.loads(SUBSETS.read_text(encoding="utf-8"))["stable_2plus_methods"]
        probe = pd.read_csv(TRAIN, nrows=16, low_memory=False)
        all_features = [c for c in probe.columns if c not in ("id", "label", "attack_cat")]
        if len(all_features) != 42 or len(stable) != 17 or len(set(stable)) != 17:
            raise RuntimeError("Frozen TRAIN feature schema mismatch")
        features = {"random_forest_17": stable, "random_forest_42": all_features, "stacking_42": all_features}
        for name in RUNS:
            try:
                item = verify_one(name, features[name], frozen, probe, versions)
            except Exception as exc:
                item = {"candidate": name, "passed": False,
                        "failure": type(exc).__name__ + ": " + str(exc)[:200]}
            results["results"][name] = item
            print(name + ": " + ("PASS" if item["passed"] else "FAIL"), flush=True)
        results["passed"] = all(item["passed"] for item in results["results"].values())
        results["environment"] = versions
        results["frozen_input_sha256"] = HASHES
    except Exception as exc:
        results["failure"] = type(exc).__name__ + ": " + str(exc)[:200]
    finally:
        (target / "artifact_acceptance.json").write_text(
            json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8"
        )
    print(json.dumps({"passed": results["passed"], "report": str(target / "artifact_acceptance.json")}))
    return 0 if results["passed"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
